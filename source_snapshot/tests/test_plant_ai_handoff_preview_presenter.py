def test_presenter_payload_splits_allowed_and_blocked_outputs() -> None:
    payload = build_rice_albumin_handoff_preview_payload()

    assert payload["allowed_outputs"][0] == "design_intent"
    assert payload["blocked_outputs"][-1] == "wet_lab_readiness_claim"
    allowed = {row["Output"] for row in payload["allowed_output_rows"]}
    blocked = {row["Output"] for row in payload["blocked_output_rows"]}
    boundaries = {row["Preview boundary"] for row in payload["allowed_output_rows"] + payload["blocked_output_rows"]}

    assert "design intent" in allowed
    assert "company handoff draft" in allowed
    assert "primer design" in blocked
    assert "yield prediction" in blocked
    assert "final construct recommendation" in blocked
    assert "visible only as documentation draft context" in boundaries
    assert "blocked; not generated by this read-only preview" in boundaries


def test_presenter_reuses_shared_preview_contract_row_builder() -> None:
    payload = build_rice_albumin_handoff_preview_payload()
    shared_contract = build_preview_contract_rows(
        scope_category=payload["scope_category"],
        allowed_outputs=payload["allowed_outputs"],
        blocked_outputs=payload["blocked_outputs"],
        boundary_statements=payload["boundary_statements"],
        parsed_intent_pairs=[
            ("Plant host", "rice"),
            ("Tissue/context", "seed"),
            ("Target", "albumin-like protein"),
            ("Handoff goal", "company-facing design evaluation package"),
        ],
        persistent=payload["persistent"],
        allowed_output_boundary_label="visible only as documentation draft context",
    )

    assert payload["preview_status"] == shared_contract["preview_status"]
    assert payload["allowed_outputs"] == shared_contract["allowed_outputs"]
    assert payload["blocked_outputs"] == shared_contract["blocked_outputs"]
    assert payload["boundary_statements"] == shared_contract["boundary_statements"]
    assert payload["parsed_intent_rows"] == shared_contract["parsed_intent_rows"]
    assert payload["persistent"] is shared_contract["persistent"]
    assert payload["allowed_output_rows"] == shared_contract["allowed_output_rows"]
    assert payload["blocked_output_rows"] == shared_contract["blocked_output_rows"]
    assert payload["boundary_statement_rows"] == shared_contract["boundary_statement_rows"]


def test_presenter_payload_does_not_emit_forbidden_positive_or_operational_content() -> None:
    payload = build_rice_albumin_handoff_preview_payload()
    generated_preview = dict(payload)
    generated_preview["blocked_output_rows"] = []
    text = _payload_text_without_allowed_negative_boundary(generated_preview)

    for phrase in FORBIDDEN_OPERATIONAL_PHRASES:
        assert phrase not in text


