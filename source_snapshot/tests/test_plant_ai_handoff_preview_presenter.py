def _term(*parts: str) -> str:
    return "".join(parts)


FORBIDDEN_OPERATIONAL_PHRASES = (
    _term("wet-lab ", "protocol"),
    _term("primer ", "sequence"),
    _term("final ", "sequence"),
    _term("synthesis", "-ready"),
    _term("transformation ", "efficiency"),
    _term("yield ", "prediction"),
    _term("guaran", "teed"),
    _term("valid", "ated"),
    _term("wet lab ", "ready"),
    _term("culture ", "conditions"),
    _term("cloning ", "steps"),
)


def _payload_text_without_allowed_negative_boundary(value: object) -> str:
    return str(value).casefold().replace("not an experimental protocol", "")


def test_presenter_returns_readable_payload_from_r102_draft() -> None:
    payload = build_rice_albumin_handoff_preview_payload()

    assert payload["title"] == "AI-guided Plant Design Handoff Preview"
    assert "deterministic fixture" in payload["subtitle"]
    assert payload["batch"] == "v2.7-r113"
    assert payload["read_only"] is True
    assert payload["persistent"] is False
    assert payload["preview_status"] == "supported plant mock preview"
    assert payload["status_badges"][0] == {
        "label": "Preview status",
        "value": "supported plant mock preview",
        "tone": "neutral",
    }
    assert payload["empty_state"]["is_empty"] is False
    assert payload["source_request"].startswith("I want to express an albumin-like protein")
    assert len(payload["handoff_section_rows"]) == 12
    assert {row["Title"] for row in payload["handoff_section_rows"]} >= {
        "Original User Request",
        "Parsed Design Intent",
        "Plant Design Context",
        "Construct Draft Slot Scaffold",
        "Boundary Statement",
    }


